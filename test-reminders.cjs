const assert=require('node:assert/strict'),M=require('./app/model.js'),R=require('./app/reminder-core.js');
const t=Date.parse('2026-11-07T12:00:00Z');
const a=M.makeNote('rose',.5,.5,new Date(t).toISOString(),'12345678-1234-1234-1234-123456789012');
M.editNote(a,{title:'A real task',reminderAt:new Date(t+60000).toISOString()},new Date(t).toISOString());
assert.equal(R.due([a],t).length,0);
assert.equal(R.fresh([a],t+59999).length,0,'Never notify before the selected instant');
assert.equal(R.fresh([a],t+60000).length,1,'Notify at the boundary');
R.mark([a]);
assert.equal(R.fresh(JSON.parse(JSON.stringify([a])),t+120000).length,0,'Restart must not repeat the sound');
assert.equal(R.due([a],t+120000).length,1,'Visual nudge remains until addressed');
R.dismiss(a);assert.equal(R.due([a],t+120000).length,0);
M.editNote(a,{reminderAt:new Date(t+180000).toISOString()},new Date(t).toISOString());
assert.equal(a.reminderFiredFor,'');assert.equal(a.reminderDismissedFor,'');
R.mark([a]);R.snooze(a,t+180000);
assert.equal(R.fresh([a],t+779999).length,0);
assert.equal(R.fresh([a],t+780000).length,1,'Snooze fires once after ten minutes');
R.mark([a]);assert.equal(R.fresh([a],t+780001).length,0);
a.completed=new Date(t).toISOString();assert.equal(R.due([a],t+999999).length,0);
a.completed=null;assert.equal(R.due([a],t+999999).length,1);
a.reminderAt='invalid';assert.equal(R.due([a],t+999999).length,0);
a.reminderAt=new Date(t).toISOString();a.title='';a.todo='';assert.equal(R.due([a],t+999999).length,0);
a.title='Task';a.reminderDismissedFor='';a.reminderFiredFor='';a.reminderSnoozedUntil='';
const b={...a,id:'another'};
const batch=R.fresh([a,b],t);assert.equal(batch.length,2);R.mark(batch);
assert.equal(R.fresh([a,b],t).length,0,'A grouped batch is claimed once');
M.editNote(a,{reminderAt:''},new Date(t).toISOString());assert.equal(R.due([a],t).length,0);
assert.equal(R.fromLocal('invalid'),'');assert.equal(R.fromLocal('2026-02-30T12:00'),'');
const local='2026-11-07T15:30';assert.equal(R.toLocal(R.fromLocal(local)),local,'Local time must round-trip');
assert.equal(R.instant('2026-11-07T15:00:00+03:00'),t,'Time zone offsets resolve to the same instant');
console.log('PASS: reminder boundary, local/UTC conversion, old notes, restart deduplication, snooze, dismiss, completion, grouped notifications');
